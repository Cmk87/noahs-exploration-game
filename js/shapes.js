function samplePoints(segs){
  const pts=[];
  for(const s of segs){
    for(let i=0;i<=60;i++){
      const t=i/60;
      if(s.t==='l') pts.push([s.a[0]+(s.b[0]-s.a[0])*t,s.a[1]+(s.b[1]-s.a[1])*t]);
      else{const u=1-t;pts.push([
        u*u*u*s.a[0]+3*u*u*t*s.c1[0]+3*u*t*t*s.c2[0]+t*t*t*s.b[0],
        u*u*u*s.a[1]+3*u*u*t*s.c1[1]+3*u*t*t*s.c2[1]+t*t*t*s.b[1]]);}
    }
  }
  return resample(pts,34);
}
function resample(pts,n){
  const d=[0];
  for(let i=1;i<pts.length;i++) d.push(d[i-1]+Math.hypot(pts[i][0]-pts[i-1][0],pts[i][1]-pts[i-1][1]));
  const total=d[d.length-1]||1,out=[];
  for(let k=0;k<n;k++){
    const tg=total*k/(n-1); let i=1; while(i<d.length-1&&d[i]<tg) i++;
    const seg=(d[i]-d[i-1])||1,r=(tg-d[i-1])/seg;
    out.push([pts[i-1][0]+(pts[i][0]-pts[i-1][0])*r,pts[i-1][1]+(pts[i][1]-pts[i-1][1])*r]);
  }
  return out;
}
for(const k in SHAPES) SHAPES[k].pts=SHAPES[k].strokes.map(samplePoints);
